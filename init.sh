## 1. 核心指令 (Core Rules)

1. **配置优先原则**：在执行任何任务前，必须首先查阅 `docs/feishu.md`。若其中链接状态为 `已配置`，通过飞书 MCP 服务获取实时上下文；若为 `未配置`，则跳过 MCP 读取步骤，直接使用本地文档。
2. **SPEC 优先与动态演进原则**：`SPEC.md` 是项目内部技术规范的唯一来源。任何涉及架构调整、逻辑变更的代码修改，都必须同步更新至 `SPEC.md`。
3. **SPEC 首次初始化原则**：若 `SPEC.md` **不存在**或**内容为空模板**（含占位符），Dev Agent **必须**在开始任何编码前，先执行 `agents/dev.md` 中的「SPEC 自动初始化流程」。
4. **数据一致性原则**：所有 API 调用、数据结构定义，必须以从 `docs/feishu.md` 关联的链接中读取到的真实飞书数据为准（若已配置）。
5. **日志与版本记录**：所有开发或测试活动必须记录在 `devlogs/` 目录中，格式见第 4 节。
6. **Bug 双轨记录原则**：QA 发现的 Bug 必须同时记录在本地 `docs/bugs.md` 和飞书 Bug 列表（若链接已配置）。


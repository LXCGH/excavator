## 4. 日志模板规范 (devlogs)

文件名格式：`YYYY-MM-DD-[Role]-任务名.md`

每个日志文件必须以以下 YAML frontmatter 开头：

```yaml
---
date: YYYY-MM-DD
role: dev | pm | qa
task: 任务简述
related_task_id: TASK-XXX        # 关联 tasks/backlog.md 中的任务（若有）
files_changed:                   # 变更文件列表
  - src/xxx.js
  - SPEC.md
status: draft | in_progress | done | blocked
---
```

正文部分自由记录：任务背景、变更内容、验证情况等。

若功能已可测试，在日志末尾注明 `状态: 可测试 ✅`，通知 QA Agent 介入。

**日志防爆降维机制（必读）**：
1. **读取限制**：所有 AI 智能体在获取历史上下文时，**最多只允许读取 `devlogs/` 目录下最新生成的 5 份日志**。禁止一次性加载整个目录的历史日志以防止上下文窗口溢出。
2. **历史追溯**：对于更早的开发历史和架构变迁，直接查阅 `SPEC.md`、`CHANGELOG.md` 和源码本身。
3. **定期归档**：当 `devlogs/` 内的文件超过 10 个时，Dev Agent 应主动（或在用户提示下）将较早的日志核心变更总结并入项目根目录的 `CHANGELOG.md`，随后将旧日志移动至 `devlogs/archive/`。

---

## 5. 沙盒与破坏性实验机制 (Git Worktree)

> 当遇到复杂 Bug 修复或破坏性重构时，AI 辅助应当建议并引导用户通过 Git Worktree 开启平行工作区，防止污染当前主干的运行环境。

**触发场景**：
- 需要大范围修改核心代码（例如替换图形引擎、重构物理系统）。
- 用户的 `npm run dev` 正在运行，且用户明确要求进行可能导致当前环境崩溃的实验。

**AI 协作流程**：
1. **提议**：AI 建议使用 `git worktree add ../[目录名] -b [分支名]` 开辟平行空间。
2. **转移**：通知用户切换到新目录，并在新目录中进行代码生成与修改。
3. **闭环**：功能验证通过后，引导用户在新目录执行 Commit，切回主目录执行 Merge，并使用 `git worktree remove` 清理现场。

---

## 6. 跨 Agent 交接协议 (Handoff Protocol)

> 角色之间的工作交接必须通过标准交接物完成，禁止口头描述替代文档交付。

| 交接方向 | 交接物 | 格式要求 |
| :--- | :--- | :--- |
| **PM → Dev** | `tasks/backlog.md` 中的任务条目 | 包含：TaskID、任务名称、描述、涉及模块、验收标准 (AC)、优先级 |
| **Dev → QA** | 完成的代码 + 更新后的 `SPEC.md` | Dev 在 `devlogs/` 中注明"可测试"状态 |
| **QA → Dev** | `docs/bugs.md` 中的 Bug 条目 | 包含：BugID、描述、复现步骤、预期/实际结果、严重等级 |

---

## 7. 标准工作流（通用步骤）

> 各角色的详细工作流定义在各自的 `agents/*.md` 中。以下为所有角色共享的通用步骤：

1. **读取配置**：查阅 `docs/feishu.md`，根据链接状态决定是否调用 MCP。
2. **理解上下文**：阅读 `SPEC.md` 和 `devlogs/` 中最新日志，了解项目当前状态。
3. **创建日志**：在 `devlogs/` 创建本次任务日志（格式见第 4 节）。
4. **执行专属工作流**：按各角色 `agents/*.md` 中定义的步骤执行。
5. **同步文档**：若引入新架构或接口，对应角色必须更新相关文档。
6. **最终确认**：确保代码、本地 SPEC 与飞书文档三方一致（若飞书已配置）。

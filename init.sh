## 3. SPEC.md 模板规范

当 AI 需要创建或重构 `SPEC.md` 时，**必须**严格遵循以下结构，禁止随意删减：

1. **项目概述**：项目背景、核心价值。
2. **核心功能规范**：功能描述、业务逻辑、验收标准 (AC)。
3. **技术架构**：核心技术栈、关键设计决策、模块职责说明。
4. **数据模型与接口规范**：数据实体定义、明确声明接口以飞书为准。
5. **编码约定**：引用本文件第 2 节。
6. **非功能性需求**：性能指标、安全性、兼容性。
7. **变更记录**：版本历史追踪（含关联日志列）。

